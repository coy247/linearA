/*
 * compress_sha2hw — ARM SHA2 hardware compress F(state, block) → result.
 *
 * Processes all 64 rounds in 16 groups of 4 using SHA256H/SHA256H2.
 * Schedule expansion (W[16..63]) is performed inline with vsha256su0/su1,
 * pipelined two groups ahead of consumption — no W[] scratch array needed.
 *
 * Calling convention matches compress_sw():
 *   result[8]  — output: 8 state words after compression + add-back
 *   state[8]   — input: initial state (H_INIT or midstate)
 *   block[16]  — input: 16 message words (already uint32_t, no byte-swap)
 *
 * Schedule expansion timing (group g uses W_g; su0/su1 compute W_(g+2)):
 *   G0 su0(W0,W1)            → partial W[16..19]
 *   G1 su1(W0,W2,W3) su0(W1,W2)  → W[16..19] done, partial W[20..23]
 *   G2 su1(W1,W3,W0) su0(W2,W3)  → W[20..23] done, partial W[24..27]
 *   ...pattern repeats with period-4 rotation of W0..W3...
 *   G12 su1(W3,W1,W2)        → W[60..63] done, no more expansion
 *   G13..G15                 → consume remaining W, no expansion
 */
static void compress_sha2hw(uint32_t result[8],
                             const uint32_t state[8],
                             const uint32_t block[16]) {
    /* Load state */
    uint32x4_t ABCD  = vld1q_u32(state);
    uint32x4_t EFGH  = vld1q_u32(state + 4);
    const uint32x4_t ABCD0 = ABCD;
    const uint32x4_t EFGH0 = EFGH;

    /* Load message block W[0..15] */
    uint32x4_t W0 = vld1q_u32(block);
    uint32x4_t W1 = vld1q_u32(block + 4);
    uint32x4_t W2 = vld1q_u32(block + 8);
    uint32x4_t W3 = vld1q_u32(block + 12);

    uint32x4_t T0, T1;

    /*
     * SHA4(ki, wm): process 4 rounds using message words wm + K[ki..ki+3].
     * T1 saves ABCD before update (required by SHA256H2 calling convention).
     * wm is captured by value before any subsequent schedule mutation.
     */
#define SHA4(ki, wm) \
    T0 = vaddq_u32((wm), vld1q_u32(&K[(ki)])); \
    T1 = ABCD; \
    ABCD = vsha256hq_u32(ABCD, EFGH, T0); \
    EFGH = vsha256h2q_u32(EFGH, T1, T0)

    /* ── Rounds 0-3: W[0..3] ── */
    SHA4(0,  W0);
    W0 = vsha256su0q_u32(W0, W1);               /* partial W[16..19] */

    /* ── Rounds 4-7: W[4..7] ── */
    SHA4(4,  W1);
    W0 = vsha256su1q_u32(W0, W2, W3);           /* W[16..19] complete */
    W1 = vsha256su0q_u32(W1, W2);               /* partial W[20..23] */

    /* ── Rounds 8-11: W[8..11] ── */
    SHA4(8,  W2);
    W1 = vsha256su1q_u32(W1, W3, W0);           /* W[20..23] complete */
    W2 = vsha256su0q_u32(W2, W3);               /* partial W[24..27] */

    /* ── Rounds 12-15: W[12..15] ── */
    SHA4(12, W3);
    W2 = vsha256su1q_u32(W2, W0, W1);           /* W[24..27] complete */
    W3 = vsha256su0q_u32(W3, W0);               /* partial W[28..31] */

    /* ── Rounds 16-19: W[16..19] ── */
    SHA4(16, W0);
    W3 = vsha256su1q_u32(W3, W1, W2);           /* W[28..31] complete */
    W0 = vsha256su0q_u32(W0, W1);               /* partial W[32..35] */

    /* ── Rounds 20-23: W[20..23] ── */
    SHA4(20, W1);
    W0 = vsha256su1q_u32(W0, W2, W3);           /* W[32..35] complete */
    W1 = vsha256su0q_u32(W1, W2);               /* partial W[36..39] */

    /* ── Rounds 24-27: W[24..27] ── */
    SHA4(24, W2);
    W1 = vsha256su1q_u32(W1, W3, W0);           /* W[36..39] complete */
    W2 = vsha256su0q_u32(W2, W3);               /* partial W[40..43] */

    /* ── Rounds 28-31: W[28..31] ── */
    SHA4(28, W3);
    W2 = vsha256su1q_u32(W2, W0, W1);           /* W[40..43] complete */
    W3 = vsha256su0q_u32(W3, W0);               /* partial W[44..47] */

    /* ── Rounds 32-35: W[32..35] ── */
    SHA4(32, W0);
    W3 = vsha256su1q_u32(W3, W1, W2);           /* W[44..47] complete */
    W0 = vsha256su0q_u32(W0, W1);               /* partial W[48..51] */

    /* ── Rounds 36-39: W[36..39] ── */
    SHA4(36, W1);
    W0 = vsha256su1q_u32(W0, W2, W3);           /* W[48..51] complete */
    W1 = vsha256su0q_u32(W1, W2);               /* partial W[52..55] */

    /* ── Rounds 40-43: W[40..43] ── */
    SHA4(40, W2);
    W1 = vsha256su1q_u32(W1, W3, W0);           /* W[52..55] complete */
    W2 = vsha256su0q_u32(W2, W3);               /* partial W[56..59] */

    /* ── Rounds 44-47: W[44..47] ── */
    SHA4(44, W3);
    W2 = vsha256su1q_u32(W2, W0, W1);           /* W[56..59] complete */
    W3 = vsha256su0q_u32(W3, W0);               /* partial W[60..63] */

    /* ── Rounds 48-51: W[48..51] ── schedule expansion complete after su1 */
    SHA4(48, W0);
    W3 = vsha256su1q_u32(W3, W1, W2);           /* W[60..63] complete */

    /* ── Rounds 52-63: consume remaining W, no expansion needed ── */
    SHA4(52, W1);
    SHA4(56, W2);
    SHA4(60, W3);

#undef SHA4

    /* Add compressed chunk back to initial state (Davies-Meyer construction) */
    vst1q_u32(result,     vaddq_u32(ABCD, ABCD0));
    vst1q_u32(result + 4, vaddq_u32(EFGH, EFGH0));
}

/*
 * Interleaved 4-way macros — 4 independent lanes fill the SHA256H latency pipeline.
 * SHA256H has a 6-cycle latency on M2; issuing 4 independent chains keeps the pipe fed.
 * T0/T1 are shared scratch regs reused per lane (sequential expansions, no conflict).
 */

/* 4 rounds for one lane; T1 captures A before update (SHA256H2 calling convention). */
#define R4H(ki, wm, A, E) \
    T0 = vaddq_u32((wm), vld1q_u32(&K[(ki)])); \
    T1 = (A); \
    (A) = vsha256hq_u32((A), (E), T0); \
    (E) = vsha256h2q_u32((E), T1, T0)

/* su0 partial schedule step for all 4 lanes: di = su0(di, si) */
#define SU0ALL(d0, d1, d2, d3, s0, s1, s2, s3) \
    (d0) = vsha256su0q_u32((d0), (s0)); \
    (d1) = vsha256su0q_u32((d1), (s1)); \
    (d2) = vsha256su0q_u32((d2), (s2)); \
    (d3) = vsha256su0q_u32((d3), (s3))

/* su1 final schedule step for all 4 lanes: di = su1(di, ai, bi) */
#define SU1ALL(d0, d1, d2, d3, a0, a1, a2, a3, xb0, xb1, xb2, xb3) \
    (d0) = vsha256su1q_u32((d0), (a0), (xb0)); \
    (d1) = vsha256su1q_u32((d1), (a1), (xb1)); \
    (d2) = vsha256su1q_u32((d2), (a2), (xb2)); \
    (d3) = vsha256su1q_u32((d3), (a3), (xb3))

/* 4 rounds for all 4 lanes using their respective W-vector. */
#define R4ALL(ki, v0, v1, v2, v3) \
    R4H(ki, v0, A0, E0); \
    R4H(ki, v1, A1, E1); \
    R4H(ki, v2, A2, E2); \
    R4H(ki, v3, A3, E3)

/*
 * compress_sha2hw_4way — 4-lane interleaved ARM SHA2 compression.
 *
 * All 4 lanes share the same initial state (midstate or H_INIT for mining).
 * Each lane gets its own 16-word block (b0..b3), differing in the nonce word.
 *
 * Register budget: 2 save + 4×2 state + 4×4 W + 2 temps = 28 NEON regs.
 * ARM64 has v0-v31 (32 regs) — fits with 4 to spare.
 */
static void compress_sha2hw_4way(
    uint32_t r0[8], uint32_t r1[8], uint32_t r2[8], uint32_t r3[8],
    const uint32_t state[8],
    const uint32_t b0[16], const uint32_t b1[16],
    const uint32_t b2[16], const uint32_t b3[16])
{
    /* Load shared initial state; SA/SE are the save copies for Davies-Meyer add-back */
    uint32x4_t SA = vld1q_u32(state),     SE = vld1q_u32(state + 4);
    uint32x4_t A0 = SA, E0 = SE;
    uint32x4_t A1 = SA, E1 = SE;
    uint32x4_t A2 = SA, E2 = SE;
    uint32x4_t A3 = SA, E3 = SE;

    /* Load per-lane message blocks W[0..15] */
    uint32x4_t w00 = vld1q_u32(b0),      w01 = vld1q_u32(b1),
               w02 = vld1q_u32(b2),      w03 = vld1q_u32(b3);
    uint32x4_t w10 = vld1q_u32(b0 + 4),  w11 = vld1q_u32(b1 + 4),
               w12 = vld1q_u32(b2 + 4),  w13 = vld1q_u32(b3 + 4);
    uint32x4_t w20 = vld1q_u32(b0 + 8),  w21 = vld1q_u32(b1 + 8),
               w22 = vld1q_u32(b2 + 8),  w23 = vld1q_u32(b3 + 8);
    uint32x4_t w30 = vld1q_u32(b0 + 12), w31 = vld1q_u32(b1 + 12),
               w32 = vld1q_u32(b2 + 12), w33 = vld1q_u32(b3 + 12);

    uint32x4_t T0, T1;

    /* G0:  rounds  0-3;  su0(W0→W1) */
    R4ALL(0,  w00, w01, w02, w03);
    SU0ALL(w00, w01, w02, w03,  w10, w11, w12, w13);

    /* G1:  rounds  4-7;  su1(W0,W2,W3);  su0(W1→W2) */
    R4ALL(4,  w10, w11, w12, w13);
    SU1ALL(w00, w01, w02, w03,  w20, w21, w22, w23,  w30, w31, w32, w33);
    SU0ALL(w10, w11, w12, w13,  w20, w21, w22, w23);

    /* G2:  rounds  8-11; su1(W1,W3,W0);  su0(W2→W3) */
    R4ALL(8,  w20, w21, w22, w23);
    SU1ALL(w10, w11, w12, w13,  w30, w31, w32, w33,  w00, w01, w02, w03);
    SU0ALL(w20, w21, w22, w23,  w30, w31, w32, w33);

    /* G3:  rounds 12-15; su1(W2,W0,W1);  su0(W3→W0) */
    R4ALL(12, w30, w31, w32, w33);
    SU1ALL(w20, w21, w22, w23,  w00, w01, w02, w03,  w10, w11, w12, w13);
    SU0ALL(w30, w31, w32, w33,  w00, w01, w02, w03);

    /* G4:  rounds 16-19; su1(W3,W1,W2);  su0(W0→W1) */
    R4ALL(16, w00, w01, w02, w03);
    SU1ALL(w30, w31, w32, w33,  w10, w11, w12, w13,  w20, w21, w22, w23);
    SU0ALL(w00, w01, w02, w03,  w10, w11, w12, w13);

    /* G5:  rounds 20-23; su1(W0,W2,W3);  su0(W1→W2) */
    R4ALL(20, w10, w11, w12, w13);
    SU1ALL(w00, w01, w02, w03,  w20, w21, w22, w23,  w30, w31, w32, w33);
    SU0ALL(w10, w11, w12, w13,  w20, w21, w22, w23);

    /* G6:  rounds 24-27; su1(W1,W3,W0);  su0(W2→W3) */
    R4ALL(24, w20, w21, w22, w23);
    SU1ALL(w10, w11, w12, w13,  w30, w31, w32, w33,  w00, w01, w02, w03);
    SU0ALL(w20, w21, w22, w23,  w30, w31, w32, w33);

    /* G7:  rounds 28-31; su1(W2,W0,W1);  su0(W3→W0) */
    R4ALL(28, w30, w31, w32, w33);
    SU1ALL(w20, w21, w22, w23,  w00, w01, w02, w03,  w10, w11, w12, w13);
    SU0ALL(w30, w31, w32, w33,  w00, w01, w02, w03);

    /* G8:  rounds 32-35; su1(W3,W1,W2);  su0(W0→W1) */
    R4ALL(32, w00, w01, w02, w03);
    SU1ALL(w30, w31, w32, w33,  w10, w11, w12, w13,  w20, w21, w22, w23);
    SU0ALL(w00, w01, w02, w03,  w10, w11, w12, w13);

    /* G9:  rounds 36-39; su1(W0,W2,W3);  su0(W1→W2) */
    R4ALL(36, w10, w11, w12, w13);
    SU1ALL(w00, w01, w02, w03,  w20, w21, w22, w23,  w30, w31, w32, w33);
    SU0ALL(w10, w11, w12, w13,  w20, w21, w22, w23);

    /* G10: rounds 40-43; su1(W1,W3,W0);  su0(W2→W3) */
    R4ALL(40, w20, w21, w22, w23);
    SU1ALL(w10, w11, w12, w13,  w30, w31, w32, w33,  w00, w01, w02, w03);
    SU0ALL(w20, w21, w22, w23,  w30, w31, w32, w33);

    /* G11: rounds 44-47; su1(W2,W0,W1);  su0(W3→W0) */
    R4ALL(44, w30, w31, w32, w33);
    SU1ALL(w20, w21, w22, w23,  w00, w01, w02, w03,  w10, w11, w12, w13);
    SU0ALL(w30, w31, w32, w33,  w00, w01, w02, w03);

    /* G12: rounds 48-51; su1(W3,W1,W2) — last schedule expansion */
    R4ALL(48, w00, w01, w02, w03);
    SU1ALL(w30, w31, w32, w33,  w10, w11, w12, w13,  w20, w21, w22, w23);

    /* G13-G15: consume remaining W, no more expansion needed */
    R4ALL(52, w10, w11, w12, w13);
    R4ALL(56, w20, w21, w22, w23);
    R4ALL(60, w30, w31, w32, w33);

#undef R4H
#undef R4ALL
#undef SU0ALL
#undef SU1ALL

    /* Davies-Meyer add-back for all 4 lanes */
    vst1q_u32(r0,     vaddq_u32(A0, SA)); vst1q_u32(r0 + 4, vaddq_u32(E0, SE));
    vst1q_u32(r1,     vaddq_u32(A1, SA)); vst1q_u32(r1 + 4, vaddq_u32(E1, SE));
    vst1q_u32(r2,     vaddq_u32(A2, SA)); vst1q_u32(r2 + 4, vaddq_u32(E2, SE));
    vst1q_u32(r3,     vaddq_u32(A3, SA)); vst1q_u32(r3 + 4, vaddq_u32(E3, SE));
}

