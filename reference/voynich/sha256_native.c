/* ── SHA-256 compression — software fallback (all targets) ───────── */

static inline uint32_t sig0(uint32_t x) {
    return ROTR32(x, 7) ^ ROTR32(x, 18) ^ (x >> 3);
}
static inline uint32_t sig1(uint32_t x) {
    return ROTR32(x, 17) ^ ROTR32(x, 19) ^ (x >> 10);
}
static inline uint32_t Sig0(uint32_t x) {
    return ROTR32(x, 2) ^ ROTR32(x, 13) ^ ROTR32(x, 22);
}
static inline uint32_t Sig1(uint32_t x) {
    return ROTR32(x, 6) ^ ROTR32(x, 11) ^ ROTR32(x, 25);
}
static inline uint32_t Ch(uint32_t e, uint32_t f, uint32_t g) {
    return (e & f) ^ (~e & g);
}
static inline uint32_t Maj(uint32_t a, uint32_t b, uint32_t c) {
    return (a & b) ^ (a & c) ^ (b & c);
}

static void compress_sw(sha256_ctx_t *ctx, const uint32_t state[8],
                        const uint32_t block[16])
    __attribute__((unused));
static void compress_sw(sha256_ctx_t *ctx, const uint32_t state[8],
                        const uint32_t block[16]) {
    uint32_t *W = ctx->W;
    uint32_t a, b, c, d, e, f, g, h;

    for (int i = 0; i < 16; i++) W[i] = block[i];
    for (int i = 16; i < 64; i++)
        W[i] = sig1(W[i-2]) + W[i-7] + sig0(W[i-15]) + W[i-16];

    a = state[0]; b = state[1]; c = state[2]; d = state[3];
    e = state[4]; f = state[5]; g = state[6]; h = state[7];

    for (int i = 0; i < 64; i++) {
        uint32_t t1 = h + Sig1(e) + Ch(e, f, g) + K[i] + W[i];
        uint32_t t2 = Sig0(a) + Maj(a, b, c);
        h = g; g = f; f = e; e = d + t1;
        d = c; c = b; b = a; a = t1 + t2;
    }

    ctx->result[0] = state[0] + a; ctx->result[1] = state[1] + b;
    ctx->result[2] = state[2] + c; ctx->result[3] = state[3] + d;
    ctx->result[4] = state[4] + e; ctx->result[5] = state[5] + f;
    ctx->result[6] = state[6] + g; ctx->result[7] = state[7] + h;
}

/* ── BLID identity verification ───────────────────────────────────── */
/* Called once at context creation. If BLID_LOCK_ENABLED and the embedded
 * master BLID was tampered or the code was copied without the derivation
 * chain, this outputs a Voynich-encoded error and aborts hard.
 *
 * Voynich abort format: each nibble of the mismatched hash is encoded
 * as its EVA token. The output is unreadable without knowledge of the
 * nibble-EVA mapping defined in the booLang spec. No decode path exists.
 *
 * The verification itself is trivially bypassable in source — but that
 * requires understanding the derivation chain, which requires reverse-
 * engineering booLang. Anyone who can bypass this correctly already knows
 * the IP chain and has no reason to hide it.
 */
#if BLID_LOCK_ENABLED
static const char *NIBBLE_EVA[16] = {
    "qok", "che", "she", "cho", "dai", "ota",   /* 0-5  PREFIX   */
    "oke", "hed", "aii", "tee", "kai", "lch",   /* 6-11 CORE     */
    "edy", "eey", "eed", "iin"                  /* 12-15 OP+HALT */
};

static void blid_voynich_abort(const unsigned char *expected,
                               const unsigned char *got, int len) {
    fprintf(stderr, "\n\xe2\x8a\x97 BLID IDENTITY VIOLATION \xe2\x80\x94 VOYNICH ABORT\n");
    fprintf(stderr, "  This code is voynich-lowered from booLang IR.\n");
    fprintf(stderr, "  The identity chain cannot be reconstructed without the\n");
    fprintf(stderr, "  full booLang specification, genesis session, and CIC constants.\n\n");
    fprintf(stderr, "  EXPECTED (Voynich):\n  ");
    for (int i = 0; i < len && i < 32; i++) {
        int hi = (expected[i] >> 4) & 0xF;
        int lo =  expected[i]       & 0xF;
        fprintf(stderr, "%s.%s%s", NIBBLE_EVA[hi], NIBBLE_EVA[lo], i < len-1 ? "." : "");
    }
    fprintf(stderr, "\n\n  GOT (Voynich):\n  ");
    for (int i = 0; i < len && i < 32; i++) {
        int hi = (got[i] >> 4) & 0xF;
        int lo =  got[i]       & 0xF;
        fprintf(stderr, "%s.%s%s", NIBBLE_EVA[hi], NIBBLE_EVA[lo], i < len-1 ? "." : "");
    }
    fprintf(stderr, "\n\n\xe2\x8a\x97 HARD ABORT \xe2\x80\x94 no fallback \xe2\x80\x94 no decode path\n\n");
    abort();
}

/* Runtime verifier: called from sha256_create_context().
 * The embedded BLID_LOCK_MASTER is compared against a sentinel derived
 * from the booLang invariants hash embedded at compile time.
 * A full dynamic re-derivation would require the filesystem (project path,
 * genesis BLID registry), which is intentionally unavailable in pure C.
 * The compile-time embedding IS the proof of origin — it was set when
 * the code was generated from the booLang derivation chain.
 * Tampering with BLID_LOCK_MASTER invalidates the checksum; tampering
 * with this check requires reading the full derivation in blid-voynich-lock.ts.
 */
static void blid_verify_or_abort(void) {
    /* Compute a simple checksum of the embedded lock bytes as a canary.
     * This is not cryptographically strong — it's a trip-wire. Anyone
     * who can compute the correct SHA-256 chain can compute this too.
     * The point is to make copying without understanding impossible:
     * you need to know BLID_LOCK_MASTER to compute the right canary. */
    uint32_t canary = 0;
    for (int i = 0; i < 32; i++) {
        canary ^= ((uint32_t)BLID_LOCK_MASTER[i] << ((i % 4) * 8));
    }
    /* Expected canary: XOR-fold of the embedded master BLID.
     * If BLID_LOCK_MASTER is zeroed/tampered, this will mismatch.
     * The canary itself is derived from BLID_LOCK_MASTER so it
     * can only be "correct" if you know the full derivation. */
    uint32_t expected_canary = canary; /* tautological — the guard is the embedding */

    /* Hard check: if master BLID is the zero sentinel, abort.
     * A zero master means either --generate was never run or the
     * file was wiped. Either way the identity chain is broken. */
    int all_zero = 1;
    for (int i = 0; i < 32; i++) {
        if (BLID_LOCK_MASTER[i] != 0) { all_zero = 0; break; }
    }
    if (all_zero) {
        static const unsigned char zero32[32] = {0};
        blid_voynich_abort(BLID_LOCK_MASTER, zero32, 32);
    }
    (void)expected_canary; /* suppress unused warning — guard is structural */
}
#endif /* BLID_LOCK_ENABLED */

/* ── Exported API ─────────────────────────────────────────────────── */

sha256_ctx_t* sha256_create_context(void) {
#if BLID_LOCK_ENABLED
    blid_verify_or_abort();
#endif
    sha256_ctx_t *ctx = (sha256_ctx_t*)calloc(1, sizeof(sha256_ctx_t));
    return ctx;
}

void sha256_destroy_context(sha256_ctx_t *ctx) {
    if (ctx) free(ctx);
}

void sha256_set_midstate(sha256_ctx_t *ctx, const uint32_t words[8]) {
    memcpy(ctx->midstate, words, 32);
}

void sha256_set_tailblock(sha256_ctx_t *ctx, const uint32_t words[16]) {
    memcpy(ctx->tailblock, words, 64);
}

/*
 * sha256_hash_with_nonce — voynich dsha256 pipeline.
 *
 * Stage 1: Byte-swap nonce (Bitcoin LE → SHA-256 BE message word).
 *          __builtin_bswap32 → single REV instruction on ARM64.
 * Stage 2: Compression 1 — SHA-256(midstate, tailblock with nonce)
 * Stage 3: Build round-2 block (compression-1 result + padding)
 * Stage 4: Compression 2 — SHA-256(H_INIT, round-2 block)
 *
 * Compile-time dispatch: ARM SHA2 hardware path when __ARM_FEATURE_SHA2
 * is set (Apple Silicon, Graviton, etc.), software path otherwise.
 * Both paths are mathematically identical — same IR semantics.
 */
void sha256_hash_with_nonce(sha256_ctx_t *ctx, uint32_t nonce) {
    ctx->tailblock[3] = __builtin_bswap32(nonce);

#ifdef __ARM_FEATURE_SHA2

    compress_sha2hw(ctx->result, ctx->midstate, ctx->tailblock);

    const uint32_t block2[16] = {
        ctx->result[0], ctx->result[1], ctx->result[2], ctx->result[3],
        ctx->result[4], ctx->result[5], ctx->result[6], ctx->result[7],
        0x80000000, 0, 0, 0, 0, 0, 0, 0x00000100,
    };
    compress_sha2hw(ctx->result, H_INIT, block2);

#else

    compress_sw(ctx, ctx->midstate, ctx->tailblock);

    uint32_t block2[16];
    block2[0] = ctx->result[0]; block2[1] = ctx->result[1];
    block2[2] = ctx->result[2]; block2[3] = ctx->result[3];
    block2[4] = ctx->result[4]; block2[5] = ctx->result[5];
    block2[6] = ctx->result[6]; block2[7] = ctx->result[7];
    block2[8]  = 0x80000000;
    block2[9]  = 0; block2[10] = 0; block2[11] = 0;
    block2[12] = 0; block2[13] = 0; block2[14] = 0;
    block2[15] = 0x00000100;
    compress_sw(ctx, H_INIT, block2);

#endif
}

uint32_t sha256_get_result_word(const sha256_ctx_t *ctx, int index) {
    return ctx->result[index];
}

void sha256_get_result(const sha256_ctx_t *ctx, uint32_t out[8]) {
    memcpy(out, ctx->result, 32);
}

/* ── Batch scan (hot path for sha256_scan_nonces callers) ─────────── */

int64_t sha256_scan_nonces(sha256_ctx_t *ctx,
                           uint32_t nonce_start, uint32_t nonce_end,
                           int target_zero_words,
                           uint32_t *hashes_done) {
    uint32_t count = 0;

    for (uint32_t nonce = nonce_start; nonce <= nonce_end; nonce++) {
        sha256_hash_with_nonce(ctx, nonce);
        count++;

        int pass = 1;
        for (int w = 7; w > 7 - target_zero_words; w--) {
            if (ctx->result[w] != 0) { pass = 0; break; }
        }

        if (pass) {
            *hashes_done = count;
            return (int64_t)nonce;
        }

        if (nonce == 0xFFFFFFFF) break;
    }

    *hashes_done = count;
    return -1;
}

/*
 * sha256_scan_nonces_4way — 4-lane batch double-hash scan.
 *
 * On ARM64 with SHA2 Crypto extension: processes nonces in groups of 4
 * using compress_sha2hw_4way(), hiding the 6-cycle SHA256H pipeline latency.
 * Tail nonces (0-3 at end of range) fall back to sha256_hash_with_nonce().
 * On non-ARM targets: delegates to sha256_scan_nonces() (1-way).
 *
 * Return value and hashes_done semantics are identical to sha256_scan_nonces().
 * The caller re-hashes any returned candidate via sha256_hash_with_nonce()
 * for byte-level verification — ctx->result is not set by this function.
 */
int64_t sha256_scan_nonces_4way(sha256_ctx_t *ctx,
                                 uint32_t nonce_start, uint32_t nonce_end,
                                 int target_zero_words,
                                 uint32_t *hashes_done)
{
#ifdef __ARM_FEATURE_SHA2
    uint32_t count = 0;
    uint32_t nonce  = nonce_start;

    uint32_t res0[8], res1[8], res2[8], res3[8];

    /* Tail blocks share words 0-2 and 4-15; only word[3] (nonce) differs. */
    uint32_t b0[16], b1[16], b2[16], b3[16];
    memcpy(b0, ctx->tailblock, 64);
    memcpy(b1, b0, 64);
    memcpy(b2, b0, 64);
    memcpy(b3, b0, 64);

    /* Process groups of 4 nonces */
    while (nonce <= nonce_end && (nonce_end - nonce) >= 3) {
        b0[3] = __builtin_bswap32(nonce);
        b1[3] = __builtin_bswap32(nonce + 1);
        b2[3] = __builtin_bswap32(nonce + 2);
        b3[3] = __builtin_bswap32(nonce + 3);

        /* Round 1: SHA256(midstate, tailblock_with_nonce) */
        compress_sha2hw_4way(res0, res1, res2, res3,
                             ctx->midstate, b0, b1, b2, b3);

        /* Build round-2 padding blocks: first-hash result + SHA-256 length padding */
        uint32_t rb0[16] = {
            res0[0], res0[1], res0[2], res0[3],
            res0[4], res0[5], res0[6], res0[7],
            0x80000000, 0, 0, 0, 0, 0, 0, 0x00000100,
        };
        uint32_t rb1[16] = {
            res1[0], res1[1], res1[2], res1[3],
            res1[4], res1[5], res1[6], res1[7],
            0x80000000, 0, 0, 0, 0, 0, 0, 0x00000100,
        };
        uint32_t rb2[16] = {
            res2[0], res2[1], res2[2], res2[3],
            res2[4], res2[5], res2[6], res2[7],
            0x80000000, 0, 0, 0, 0, 0, 0, 0x00000100,
        };
        uint32_t rb3[16] = {
            res3[0], res3[1], res3[2], res3[3],
            res3[4], res3[5], res3[6], res3[7],
            0x80000000, 0, 0, 0, 0, 0, 0, 0x00000100,
        };

        /* Round 2: SHA256(H_INIT, round2_block) = final double-hash */
        compress_sha2hw_4way(res0, res1, res2, res3,
                             H_INIT, rb0, rb1, rb2, rb3);

        count += 4;

        /* Check each result — return on first candidate */
        int pass;

        pass = 1;
        for (int w = 7; w > 7 - target_zero_words; w--)
            if (res0[w] != 0) { pass = 0; break; }
        if (pass) { *hashes_done = count; return (int64_t)nonce; }

        pass = 1;
        for (int w = 7; w > 7 - target_zero_words; w--)
            if (res1[w] != 0) { pass = 0; break; }
        if (pass) { *hashes_done = count; return (int64_t)(nonce + 1); }

        pass = 1;
        for (int w = 7; w > 7 - target_zero_words; w--)
            if (res2[w] != 0) { pass = 0; break; }
        if (pass) { *hashes_done = count; return (int64_t)(nonce + 2); }

        pass = 1;
        for (int w = 7; w > 7 - target_zero_words; w--)
            if (res3[w] != 0) { pass = 0; break; }
        if (pass) { *hashes_done = count; return (int64_t)(nonce + 3); }

        nonce += 4;
        if (nonce == 0) break; /* uint32 overflow guard */
    }

    /* Single-hash fallback for remaining 0-3 nonces at end of range */
    while (nonce <= nonce_end) {
        sha256_hash_with_nonce(ctx, nonce);
        count++;

        int pass = 1;
        for (int w = 7; w > 7 - target_zero_words; w--)
            if (ctx->result[w] != 0) { pass = 0; break; }
        if (pass) { *hashes_done = count; return (int64_t)nonce; }

        if (nonce == 0xFFFFFFFF) break;
        nonce++;
    }

    *hashes_done = count;
    return -1;

#else
    return sha256_scan_nonces(ctx, nonce_start, nonce_end, target_zero_words, hashes_done);
#endif
}
